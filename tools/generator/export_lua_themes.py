#!/usr/bin/env python3
"""Write murdoku.koplugin/murdoku_themes.lua from mgen/themes.py (keeps the
on-device generator's content in sync with the offline tool)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mgen import themes as T  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'murdoku.koplugin', 'murdoku_themes.lua')


def q(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    L = ['-- Generated by tools/generator/export_lua_themes.py from mgen/themes.py. Do not edit by hand.',
         'return {']
    L.append('    obj_id = {')
    for w, i in sorted(T.OBJ_ID.items()):
        L.append(f'        [{q(w)}] = {i},')
    L.append('    },')
    L.append('    two_wide = { ' + ', '.join(f'[{q(w)}] = true' for w in sorted(T.TWO_WIDE)) + ' },')
    L.append('    on_verb = {')
    for w, v in sorted(T.ON_VERB.items()):
        L.append(f'        [{q(w)}] = {q(v)},')
    L.append('    },')
    L.append('    mass = { ' + ', '.join(f'[{q(w)}] = true' for w in sorted(T.MASS)) + ' },')
    L.append('    noun = { ' + ', '.join(f'[{q(w)}] = {q(v)}' for w, v in sorted(T.NOUN.items())) + ' },')
    L.append('    themes = {')
    for name in sorted(T.THEMES):
        th = T.THEMES[name]
        L.append(f'        {{ name = {q(name)},')
        L.append('          titles = { ' + ', '.join(q(t) for t in th['titles']) + ' },')
        L.append('          rooms = {')
        for rname, pal in th['rooms']:
            L.append(f'            {{ {q(rname)}, {{ ' + ', '.join(f'{{ {q(w)}, {k} }}' for w, k in pal) + ' } },')
        L.append('          } },')
    L.append('    },')
    for key, d in (('female', T.FEMALE), ('male', T.MALE)):
        L.append(f'    {key} = {{')
        for letter in sorted(d):
            L.append(f'        {letter} = {{ ' + ', '.join(q(n) for n in d[letter]) + ' },')
        L.append('    },')
    L.append('    victim_f = { ' + ', '.join(q(n) for n in T.VICTIM_F) + ' },')
    L.append('    victim_m = { ' + ', '.join(q(n) for n in T.VICTIM_M) + ' },')
    L.append('}')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
